export function deepenIntermediateLessons(courses){
 if(!Array.isArray(courses))throw Error('Expected course list');
 const seen=new Set();
 for(const course of courses){
  const data=INTERMEDIATE_DEPTH[course.id];if(!data)continue;
  const lesson=course.lessons.find(x=>x.id===data.id);
  if(!lesson||!Array.isArray(lesson.sections)||!lesson.quiz||lesson.deepSections?.length)throw Error('Missing intermediate lesson '+course.id);
  lesson.title=data.title;lesson.deepSections=data.sections.map(s=>({...s}));
  lesson.deepExample=data.example;lesson.deepTask=data.task;
  lesson.deepRubric=[...data.criteria];lesson.deepMinutes=data.minutes;
  lesson.flow={title:'From evidence to an informed decision',steps:[
   {label:'Define the question',detail:'Separate the observation, the claim and the actual decision.'},
   {label:'Apply the method',detail:'Use the subject-specific concept rather than memorizing a slogan.'},
   {label:'Challenge the conclusion',detail:'Compare evidence, a competing explanation and meaningful uncertainty.'},
   {label:'Choose the next step',detail:'State an evidence-limited response and what would improve it.'}
  ],caption:'Reasoning guidance, not a graded certification.'};
  lesson.intermediateDepth='applied-2026';seen.add(course.id);
 }
 if(seen.size!==14)throw Error('Incomplete intermediate subjects');
 return seen.size;
}
