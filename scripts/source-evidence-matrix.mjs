/** Offline author-source traceability, not independent claim verification. */
import {createHash} from 'node:crypto';
import {isSafeReferenceURL} from '../sourcehealth.js';
const obj=x=>x!==null&&typeof x==='object'&&!Array.isArray(x);
const hash=x=>typeof x==='string'&&/^[a-f0-9]{64}$/.test(x);
const value=x=>typeof x==='string'&&x.trim().length>0;
const clean=x=>String(x??'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replace(/[\r\n]+/g,' ');
export function buildSourceEvidenceMatrix(packet){
 if(!obj(packet)||packet.status!=='review-packet-not-independent-signoff'||
  !Array.isArray(packet.lessons)||!Array.isArray(packet.decisions)||!Array.isArray(packet.references))
  throw Error('Invalid editorial author packet');
 const byUrl=new Map();
 const add=(item,kind,refs,context)=>{
  if(!obj(item)||!value(item.id)||!hash(item.contentHash)||!obj(context))
   throw Error('Invalid source context');
  if(!Array.isArray(refs)||refs.length===0)throw Error('Missing cited reference: '+item.id);
  const local=new Set();
  for(const r of refs){
   if(!obj(r)||!value(r.label)||!isSafeReferenceURL(r.url))
    throw Error('Invalid author URL: '+item.id);
   if(local.has(r.url))continue;
   local.add(r.url);
   if(!byUrl.has(r.url))byUrl.set(r.url,{
    id:createHash('sha256').update(r.url).digest('hex'),url:r.url,
    labels:[],highStakes:false,usages:[],reviewStatus:'pending-expert-claim-review',
    independentClaimApprovals:0
   });
   const entry=byUrl.get(r.url);
   if(!entry.labels.includes(r.label))entry.labels.push(r.label);
   entry.highStakes ||= item.highStakes===true;
   entry.usages.push({kind,itemId:item.id,contentHash:item.contentHash,
    highStakes:item.highStakes===true,authoredContext:context,
    humanClaimExtractionRequired:true,independentClaimValidation:false});
  }
 };
 for(const l of packet.lessons){
  if(!obj(l)||!obj(l.content)||!Array.isArray(l.content.sections)||!obj(l.content.quiz))
   throw Error('Incomplete lesson');
  const c=l.content;
  add(l,'lesson',c.references,{
   title:c.title,stage:c.stage,course:l.course,
   stageLearningObjective:c.stageLearningObjective,introduction:c.intro,
   sections:c.sections.map(s=>({heading:s.heading,body:s.body})),
   example:c.workedExample,exercise:c.task,question:c.quiz.question,
   answerOptions:[...c.quiz.options],authoredCorrectIndex:c.quiz.correct,
   authoredAnswer:c.quiz.options[c.quiz.correct],answerExplanation:c.quiz.explanation
  });
 }
 for(const q of packet.decisions){
  if(!obj(q)||!obj(q.content))throw Error('Incomplete decision');
  const c=q.content;
  add(q,'decision',c.sources,{
   title:q.id,stage:c.stage,course:c.courseId,scenario:c.question,
   answerOptions:[...c.options],authoredCorrectIndex:c.correct,
   authoredAnswer:c.options[c.correct],answerExplanation:c.explanation
  });
 }
 const catalog=new Set(packet.references.map(x=>x.url));
 if(catalog.size!==packet.references.length||catalog.size!==byUrl.size||
  [...byUrl.keys()].some(x=>!catalog.has(x)))throw Error('Source catalog differs from authored teaching usage');
 const sources=[...byUrl.values()].sort((a,b)=>a.url.localeCompare(b.url));
 return {schemaVersion:1,status:'source-usage-inventory-unreviewed',
  summary:{distinctURLs:sources.length,
   sourceUseSites:sources.reduce((n,x)=>n+x.usages.length,0),
   highStakesUseSites:sources.reduce((n,x)=>n+x.usages.filter(u=>u.highStakes).length,0),
   independentlyApprovedURLs:0,independentlyApprovedUseSites:0},
  sources,limitations:[
   'URL availability does not substantiate material claims.',
   'Expert reviewers must inspect each assertion, the source passage, jurisdiction, date and answer key.',
   'No independent source approval or gate completion is generated by this software.'
  ]};
}
export function renderSourceEvidenceWorkbook(matrix){
 if(!obj(matrix)||matrix.status!=='source-usage-inventory-unreviewed'||!Array.isArray(matrix.sources))
  throw Error('Invalid source evidence matrix');
 const out=['# XYRA Atlas — Source-to-teaching review workbook','',
  'All authored references are UNREVIEWED for claim-level expert accuracy. No approvals are generated.','',
  'Distinct URLs: '+matrix.summary.distinctURLs+
  '; cited teaching sites: '+matrix.summary.sourceUseSites+
  '; high-stakes sites: '+matrix.summary.highStakesUseSites+'.','',
  'Complete teaching contexts and exact source hashes are in the companion JSON artifact.',''];
 for(const source of matrix.sources){
  out.push('## '+clean(source.labels[0]||'External source'),'',
   'Source URL: '+clean(source.url),'','URL SHA-256: '+source.id,'',
   'Priority: '+(source.highStakes?'Specialist high-stakes review':'Independent editorial review'),'',
   'No human claim approvals. Mapped teaching items: '+source.usages.length,'');
  for(const u of source.usages){
   const c=u.authoredContext;
   out.push('### '+clean(u.itemId)+' ('+u.kind+')','',
    'Exact authored item SHA-256: '+u.contentHash,'',
    'Teaching title: '+clean(c.title),'',
    'Authored question/scenario: '+clean(c.question||c.scenario),'',
    'Authored answer (not fact checked): '+clean(c.authoredAnswer),'',
    'All answer options (NOT fact checked): '+clean(c.answerOptions.map((x,i)=>
     (i===c.authoredCorrectIndex?'[Author keyed] ':'')+'Option '+(i+1)+': '+x).join(' | ')),'',
    'Authored explanation: '+clean(c.answerExplanation),'',
    '- [ ] Extract ALL material claims from the full author content in companion JSON',
    '- [ ] Verify exact source passages and dates, jurisdiction, caveats and contradictory sources',
    '- [ ] Review the exercise, answer alternatives and expert safety concerns',
    '- [ ] Record real independent reviewer, credentials and substantiated findings',
    '- [ ] Require corrections or evidence-backed approval, never assume a URL proves truth','');
  }
 }
 return out.join('\n')+'\n';
}
